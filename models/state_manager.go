package models

import (
	"sync"
)

type ConversationStage string

const (
	ConversationStageNull                   ConversationStage = "stage_null"
	ConversationStageAddUserFood            ConversationStage = "stage_add_user_food"
	ConversationStageStart                  ConversationStage = "stage_start"
	ConversationStageAddPlanSchedule        ConversationStage = "stage_add_plan_schedule"
	ConversationStageAddMacroTargets        ConversationStage = "stage_add_macro_targets"
	ConversationStageSetDietaryRestrictions ConversationStage = "stage_set_dietary_restrictions"
	ConversationStageSetBodyWeight          ConversationStage = "stage_set_body_weight"

	// Asking for feedback on a meal plan
	ConversationStageMealPlanFeedbackBreakfast ConversationStage = "stage_meal_plan_feedback_breakfast"
	ConversationStageMealPlanFeedbackLunch     ConversationStage = "stage_meal_plan_feedback_lunch"
	ConversationStageMealPlanFeedbackDinner    ConversationStage = "stage_meal_plan_feedback_dinner"
)

type UserState struct {
	Stage ConversationStage
}

// StateManager handles thread-safe state management
type StateManager struct {
	mu sync.RWMutex
	// Maps an ID to a user state
	userStates map[uint]*UserState
	// This key is used to track accepted or rejected plans when needed.
	// Whenever we accept a plan, we clean this key, otherwise we use it
	// to pass context around about a plan that was rejected.
	lastPlan map[uint]*MealPlan
}

// NewStateManager creates a new StateManager.
//
// The function initializes the map of user IDs to UserState structs and
// returns a pointer to the new StateManager.
func NewStateManager() *StateManager {
	return &StateManager{
		userStates: make(map[uint]*UserState),
	}
}

// GetUserState retrieves the UserState for a given user ID.
//
// The function takes a StateManager and a user ID as parameters. It locks the
// map of user IDs to UserState structs, retrieves the UserState for the given
// user ID and then unlocks the map.
func (sm *StateManager) GetUserState(userID uint) UserState {
	sm.mu.RLock()
	defer sm.mu.RUnlock()

	userState, exists := sm.userStates[userID]

	if !exists {
		return UserState{Stage: ConversationStageNull}
	}

	return *userState
}

// SetUserState sets the conversation stage for a given user ID.
//
// The function takes a StateManager, a user ID and a conversation stage as
// parameters. It locks the map of user IDs to UserState structs, sets the
// conversation stage for the given user ID and then unlocks the map.
func (sm *StateManager) SetUserState(userID uint, stage ConversationStage) {
	sm.mu.Lock()
	defer sm.mu.Unlock()
	sm.userStates[userID] = &UserState{Stage: stage}
}

// GetLastPlan returns the last plan generated by the bot for a user
func (sm *StateManager) GetLastPlan(userID uint) *MealPlan {
	sm.mu.RLock()
	defer sm.mu.RUnlock()

	userLastPlan, exists := sm.lastPlan[userID]

	if !exists {
		return nil
	}

	return userLastPlan
}

// SetLastPlan sets the last plan generated by the bot for a user
func (sm *StateManager) SetLastPlan(userID uint, plan *MealPlan) {
	sm.mu.Lock()
	defer sm.mu.Unlock()
	sm.lastPlan[userID] = plan
}
